  const AppLanguage(this.code, this.nativeName, this.isRtl);

  final String code;
  final String nativeName;
  final bool isRtl;

  Locale get materialLocale =>
      this == AppLanguage.nigerianPidgin ? const Locale('en') : Locale(code);
}

